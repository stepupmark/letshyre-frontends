// Renders docs/baseline/content-inventory.md from the legacy English catalogs
// and the decisions in content-decisions.ts. Fails if a key matches no rule,
// so new legacy keys can't slip through undecided.
// Usage: node tooling/baseline/content-inventory.ts

import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { MARKETING_NAMESPACES, RULES, type Decision } from "./content-decisions.ts"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..")
const MESSAGES = existingDir([
  join(ROOT, "apps/legacy/app/i18n/messages"),
  join(ROOT, "app/i18n/messages"),
])
const OUT = join(ROOT, "docs/baseline/content-inventory.md")

function existingDir(candidates: string[]) {
  for (const dir of candidates) {
    try {
      readdirSync(dir)
      return dir
    } catch {}
  }
  throw new Error(`content-inventory: no catalogs found in ${candidates.join(" or ")}`)
}

type Json = string | number | boolean | null | Json[] | { [k: string]: Json }

// Objects are walked; arrays and scalars are leaves (they translate as a unit).
function flatten(value: Json, prefix = ""): [string, Json][] {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    return Object.entries(value).flatMap(([k, v]) => flatten(v, prefix ? `${prefix}.${k}` : k))
  }
  return [[prefix, value]]
}

const readCatalog = (locale: string, ns: string) => {
  try {
    return new Map(flatten(JSON.parse(readFileSync(join(MESSAGES, locale, `${ns}.json`), "utf8"))))
  } catch {
    return new Map<string, Json>()
  }
}

const toRegex = (pattern: string) =>
  new RegExp(`^${pattern.replace(/[.+?^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*")}$`)
const compiled = RULES.map((rule) => ({ ...rule, re: toRegex(rule.pattern) }))

const locales = readdirSync(MESSAGES).filter((d) => d !== "en" && !d.includes("."))

const preview = (value: Json) => {
  const text = typeof value === "string" ? value : JSON.stringify(value)
  const clipped = text.length > 120 ? `${text.slice(0, 117)}…` : text
  return clipped.replace(/\|/g, "\\|").replace(/\n/g, " ")
}

type Row = { key: string; english: Json; decision: Decision; note: string; translated: number }
const sections: { ns: string; rows: Row[] }[] = []
const undecided: string[] = []

for (const ns of MARKETING_NAMESPACES) {
  const english = readCatalog("en", ns)
  const others = locales.map((l) => readCatalog(l, ns))
  const rows: Row[] = []
  for (const [key, value] of english) {
    const id = `${ns}:${key}`
    const rule = compiled.find((r) => r.re.test(id))
    if (!rule) {
      undecided.push(id)
      continue
    }
    rows.push({
      key,
      english: value,
      decision: rule.decision,
      note: rule.note ?? "",
      translated: others.filter((catalog) => catalog.has(key)).length,
    })
  }
  sections.push({ ns, rows })
}

if (undecided.length) {
  console.error(`content-inventory: no rule for ${undecided.length} keys:\n  ${undecided.join("\n  ")}`)
  process.exit(1)
}

const DECISIONS: Decision[] = ["keep", "rewrite", "drop", "move"]
const count = (rows: Row[], d: Decision) => rows.filter((r) => r.decision === d).length
const all = sections.flatMap((s) => s.rows)

const lines = [
  "# Marketing content inventory (step 0.3)",
  "",
  "> Generated by `node tooling/baseline/content-inventory.ts` from the legacy English catalogs and the",
  "> proposed rules in [`tooling/baseline/content-decisions.ts`](../../tooling/baseline/content-decisions.ts).",
  "> **To change a decision, edit that file and regenerate. Don't edit this page.**",
  "",
  "| Decision | Meaning |",
  "|---|---|",
  "| **keep** | Key carries over. Its existing translations are reused, so the page can launch in those locales on day one. |",
  "| **rewrite** | New English copy (drafted in Phase 3, approved at Gate 3). Needs translation before that page is published in other locales. |",
  "| **drop** | Not used by the redesign. |",
  "| **move** | Belongs to the dashboard app (`apps/app`), not marketing. |",
  "",
  `\`Tr.\` = how many of the ${locales.length} non-English locales already translate the key.`,
  "",
  "## Summary",
  "",
  "| Namespace | Keys | keep | rewrite | drop | move |",
  "|---|---:|---:|---:|---:|---:|",
  ...sections.map(
    (s) => `| \`${s.ns}\` | ${s.rows.length} | ${DECISIONS.map((d) => count(s.rows, d)).join(" | ")} |`
  ),
  `| **Total** | **${all.length}** | ${DECISIONS.map((d) => `**${count(all, d)}**`).join(" | ")} |`,
  "",
  "New copy the redesign needs (no legacy key): home \"Inside a scorecard\" section, pricing teaser on home,",
  "nav \"About\" and \"Log in\", footer column headings for Candidates and Legal, consent banner. These are",
  "drafted as `rewrite` work in Phase 3.",
  "",
  "**Translation reuse:** every `keep` key outside `pricing` is already translated in all",
  `${locales.length} locales. \`pricing\` is English-only today. So About, Interview, Download, Contact and the legal pages`,
  "can launch in every locale once their few `rewrite` keys are translated. Home needs its rewrites translated first.",
  "",
]

for (const { ns, rows } of sections) {
  lines.push(`## \`${ns}\``, "", "| Key | English | Decision | Tr. | Note |", "|---|---|---|---:|---|")
  for (const r of rows) {
    lines.push(`| \`${r.key}\` | ${preview(r.english)} | **${r.decision}** | ${r.translated} | ${r.note.replace(/\|/g, "\\|")} |`)
  }
  lines.push("")
}

writeFileSync(OUT, lines.join("\n"))
console.log(
  `content-inventory: ${all.length} keys → ${DECISIONS.map((d) => `${d} ${count(all, d)}`).join(", ")}`
)
